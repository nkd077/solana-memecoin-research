"""
Порог входа, выведенный из измерений, а не из интуиции.

Каждая константа здесь имеет происхождение. Если происхождения нет —
константы нет.

ЧТО ДОКАЗАНО
------------
1. Условие безубыточности на бондинг-кривой Pump.fun (Marino, Naviglio,
   Tarantelli, Lillo, arXiv 2602.14860, 655 770 токенов):

       E[r] > 0  ⟺  p(vSol) > vSol² / 115²

   Цена на кривой постоянного произведения пропорциональна квадрату
   виртуальных резервов SOL, поэтому вход при vSol и выход при 115 даёт
   множитель (115/vSol)². Не дошёл до градации — позиция обнулилась.

2. Базовая доля градаций: 0,63% (Marino, сен-окт 2025) — 1,15% (Dune,
   нач. 2026). Берём середину.

3. Ликвидность на входе — ЕДИНСТВЕННЫЙ признак, переживший проверку на
   наших данных (4577 наблюдений, обучение/проверка по времени, поправка
   Бонферрони): верхняя треть по баллу −8,3% против базы −17,5%,
   прирост +9,3 п.п., p = 0,0018.

ЧТО ОПРОВЕРГНУТО (и потому здесь не участвует)
----------------------------------------------
- Репутация кошелька по прошлым исходам: эффект 0,039, знак обратный,
  828 наблюдений. Плюс вырожденное распределение на 4577.
- Разрыв на градации: после исправления ошибки разрядности медиана на
  30 с +0,9%, знак неустойчив между половинами выборки.
- Кластер по общему спонсору: вырожден, почти у всех кошельков ноль.
- Бинарный признак «дев купил свой токен»: так делают почти все
  создатели (MemeTrans, 41 470 токенов) — разделяющей силы нет.

ГЛАВНЫЙ ВЫВОД, КОТОРЫЙ КОДИРУЕТ ЭТОТ МОДУЛЬ
-------------------------------------------
Кривая стартует с vSol = 30, что требует вероятности градации 6,8%.
Базовая доля — около 0,9%. Значит, отбор обязан поднимать вероятность
минимум в 7,6 раза ещё до того, как в кривой появится хоть один SOL
реальных денег. Ни одна из пяти проверенных нами гипотез такого подъёма
не дала. Пока не дала — DEMONSTRATED_LIFT остаётся 1.0, и ворота закрыты.

Это не пессимизм, а бухгалтерия. Когда появится проверенный признак,
его множитель ставится в DEMONSTRATED_LIFT вместе со ссылкой на прогон,
который его подтвердил, и ворота открываются сами.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field

# --- геометрия кривой -------------------------------------------------
VSOL_START = 30.0          # виртуальные резервы SOL при запуске
VSOL_GRADUATION = 115.0    # 30 виртуальных + 85 реальных в точке миграции

# --- измеренные величины ----------------------------------------------
# Опубликованная доля градаций считается на другом знаменателе, чем наша
# стратегия. Мы ловим монету при ликвидности < 3 SOL, то есть покупаем
# ВСЕ подряд с самого рождения — и на этом знаменателе измерили сами:
# 6 градаций из 4859 монет = 0,12% за 30 минут наблюдения.
# Часть монет доходит до кривой позже, поэтому истина между 0,12% и 0,89%.
# Для ворот берём наше измерение: оно про ту сделку, которую мы реально
# собираемся совершать.
BASE_GRADUATION_RATE = 0.0057
BASE_RATE_SOURCE = ("наше измерение 04.09.2026: 40 правдоподобных градаций "
                    "из 7029 монет, пойманных при ликвидности < 3 SOL, "
                    "после отсева нестандартных кривых = 0,57%. Совпадает "
                    "с опубликованными 0,63%-1,15%")

# Лучший подъём, которого мы добились отбором: число покупателей за первые
# 60 секунд. Верхняя треть даёт 0,40% градаций против базы 0,12% = ×3,2.
# В DEMONSTRATED_LIFT он НЕ попадает: на проверочной половине выборки этот
# же признак даёт медианную доходность за 15 минут −6,3% против +0,0%
# (p = 0,0003, Бонферрони 0,0017). То есть он поднимает шанс градации и
# одновременно ухудшает результат — покупка в толпу, которая уже подняла цену.
BEST_OBSERVED_LIFT = 3.2
BEST_OBSERVED_LIFT_NOTE = "число покупателей за 60 с; доходность при этом хуже"

# Во сколько раз наш отбор доказанно поднимает вероятность градации.
# 1.0 = не поднимает. Менять только вместе со ссылкой на прогон.
DEMONSTRATED_LIFT = 1.0
DEMONSTRATED_LIFT_SOURCE = (
    "пять проверенных гипотез, ни одна не дала подтверждённого подъёма; "
    "см. claude/findings_2026-09-04.md"
)

# Издержки круга на Solana: комиссии пула, приоритетная комиссия,
# проскальзывание, потери от MEV. Диапазон из независимого разбора.
ROUND_TRIP_COST_LOW = 0.032
ROUND_TRIP_COST_HIGH = 0.066


@dataclass
class EdgeVerdict:
    passes: bool
    virtual_sol: float
    required_p: float          # нужно для безубыточности
    assumed_p: float           # на что мы вправе рассчитывать
    required_lift: float       # во сколько раз отбор должен быть лучше базы
    max_justifiable_vsol: float
    reason: str
    detail: dict = field(default_factory=dict)


def required_probability(virtual_sol: float) -> float:
    """Вероятность градации, при которой вход выходит в ноль."""
    v = max(virtual_sol, 1e-9)
    return min(1.0, (v / VSOL_GRADUATION) ** 2)


def max_justifiable_vsol(lift: float = DEMONSTRATED_LIFT,
                         base: float = BASE_GRADUATION_RATE) -> float:
    """Самая поздняя точка кривой, где вход ещё оправдан при данном подъёме.

    Обращение формулы: p = vSol²/115²  →  vSol = 115·√p.
    """
    return VSOL_GRADUATION * math.sqrt(min(1.0, max(0.0, lift * base)))


def evaluate(virtual_sol: float,
             lift: float = DEMONSTRATED_LIFT,
             base: float = BASE_GRADUATION_RATE) -> EdgeVerdict:
    """Проходит ли вход при таком состоянии кривой порог безубыточности."""
    req = required_probability(virtual_sol)
    assumed = min(1.0, lift * base)
    need = req / base if base > 0 else float("inf")
    cap = max_justifiable_vsol(lift, base)
    ok = assumed >= req

    if ok:
        reason = (f"проходит: нужно {req:.1%}, отбор даёт {assumed:.1%}")
    elif cap <= VSOL_START:
        reason = (f"кривая стартует с {VSOL_START:.0f} SOL, а оправдан вход "
                  f"только до {cap:.1f} — при текущем подъёме ×{lift:.1f} "
                  f"допустимой точки входа не существует")
    else:
        reason = (f"нужно {req:.1%} вероятности градации, отбор даёт "
                  f"{assumed:.1%}; вход оправдан только до vSol {cap:.1f}")

    return EdgeVerdict(
        passes=ok, virtual_sol=virtual_sol, required_p=req, assumed_p=assumed,
        required_lift=need, max_justifiable_vsol=cap, reason=reason,
        detail={
            "liquidity_sol": max(0.0, virtual_sol - VSOL_START),
            "base_rate": base,
            "demonstrated_lift": lift,
            "round_trip_cost": (ROUND_TRIP_COST_LOW, ROUND_TRIP_COST_HIGH),
        },
    )


def explain_table() -> str:
    """Табличка для лога при старте — чтобы планка была на виду."""
    out = ["  vSol   ликв.SOL   нужно p   подъём к базе"]
    for v in (30, 35, 40, 50, 60, 70, 85, 100, 115):
        r = required_probability(v)
        out.append(f"  {v:>4}   {v - VSOL_START:>7.0f}   {r:>6.1%}   "
                   f"×{r / BASE_GRADUATION_RATE:>6.1f}")
    out.append(f"  база {BASE_GRADUATION_RATE:.2%} ({BASE_RATE_SOURCE})")
    out.append(f"  доказанный подъём отбора: ×{DEMONSTRATED_LIFT:.1f} "
               f"({DEMONSTRATED_LIFT_SOURCE})")
    out.append(f"  самая поздняя оправданная точка входа: vSol "
               f"{max_justifiable_vsol():.1f}")
    return "\n".join(out)


if __name__ == "__main__":
    print(explain_table())
    print()
    for liq in (0.5, 2, 5, 20, 55):
        v = evaluate(VSOL_START + liq)
        print(f"ликвидность {liq:>4} SOL → {'ПРОХОДИТ' if v.passes else 'ОТКАЗ'}: {v.reason}")
